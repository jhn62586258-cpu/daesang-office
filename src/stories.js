// KST 날짜 기준으로 오늘의 이야기 번호
export function todayStoryIndex() {
  const kst = new Date(Date.now() + 9 * 3600 * 1000)
  const day = Math.floor(Date.UTC(kst.getUTCFullYear(), kst.getUTCMonth(), kst.getUTCDate()) / 86400000)
  return day % STORIES.length
}
